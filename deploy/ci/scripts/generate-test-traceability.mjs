import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// W-0035 / P5-1 §6.4. Emits docs/traceability-tests.md from the TestId traits in the suite.
// Generated rather than written by hand on purpose: a hand-maintained traceability table drifts
// the moment someone renames a test, and a drifted table is worse than none — it reads as
// coverage that is no longer there. Pass --check to fail instead of writing.

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "../../..");
const outputPath = path.join(repositoryRoot, "docs/traceability-tests.md");
const checkOnly = process.argv.includes("--check");

const projects = [
  { name: "Ivr.UnitTests", kind: "unit" },
  { name: "Ivr.IntegrationTests", kind: "integration" },
  { name: "Ivr.ContractTests", kind: "contract" },
  // W-0042 / P6-3. The chaos project lives at tests/chaos rather than tests/Ivr.ChaosTests, so it
  // is listed by directory name. Without this entry the generator silently skips it and the
  // traceability table reports full coverage while five scenarios sit outside it.
  { name: "chaos", kind: "chaos" },
];

async function collectSourceFiles(directory) {
  const found = [];
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    if (entry.name === "bin" || entry.name === "obj") {
      continue;
    }

    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      found.push(...(await collectSourceFiles(full)));
    } else if (entry.name.endsWith(".cs")) {
      found.push(full);
    }
  }

  return found;
}

const rows = [];
for (const project of projects) {
  const projectRoot = path.join(repositoryRoot, "tests", project.name);
  for (const file of await collectSourceFiles(projectRoot)) {
    const content = await fs.readFile(file, "utf8");
    const lines = content.split(/\r?\n/u);
    for (let index = 0; index < lines.length; index += 1) {
      const trait = /\[Trait\("TestId",\s*"([^"]+)"\)\]/u.exec(lines[index]);
      if (trait === null) {
        continue;
      }

      // The method name is the next declaration line; it is what a reviewer greps for.
      let method = "";
      for (let ahead = index + 1; ahead < Math.min(index + 12, lines.length); ahead += 1) {
        const declaration = /public\s+(?:async\s+)?[\w<>?.\[\]]+\s+(\w+)\s*\(/u.exec(lines[ahead]);
        if (declaration !== null) {
          method = declaration[1];
          break;
        }
      }

      rows.push({
        testId: trait[1],
        kind: project.kind,
        file: path.relative(repositoryRoot, file).replaceAll("\\", "/"),
        method,
      });
    }
  }
}

rows.sort((left, right) =>
  left.testId.localeCompare(right.testId, "en") ||
  left.method.localeCompare(right.method, "en"));

const byPrefix = new Map();
for (const row of rows) {
  const prefix = row.testId.split("-").slice(0, 2).join("-");
  byPrefix.set(prefix, (byPrefix.get(prefix) ?? 0) + 1);
}

const groups = [...byPrefix.entries()].sort((left, right) =>
  left[0].localeCompare(right[0], "en"));

const report = [
  "# Test traceability — test ID to source",
  "",
  "> Generated by `deploy/ci/scripts/generate-test-traceability.mjs`. Do not edit by hand;",
  "> `UT-TRACE-01` fails when this file and the suite disagree.",
  "",
  `Total tagged tests: **${rows.length}**`,
  "",
  "## Groups",
  "",
  "| Prefix | Tagged tests |",
  "| --- | ---: |",
  ...groups.map(([prefix, count]) => `| \`${prefix}\` | ${count} |`),
  "",
  "## Tests",
  "",
  "| Test ID | Kind | Method | Source |",
  "| --- | --- | --- | --- |",
  ...rows.map((row) =>
    `| \`${row.testId}\` | ${row.kind} | \`${row.method}\` | \`${row.file}\` |`),
  "",
].join("\n");

if (checkOnly) {
  const current = await fs.readFile(outputPath, "utf8").catch(() => null);
  if (current !== report) {
    process.stderr.write(
      "TEST_TRACEABILITY_DRIFT: docs/traceability-tests.md is stale. " +
        "Run node deploy/ci/scripts/generate-test-traceability.mjs\n",
    );
    process.exit(1);
  }

  process.stdout.write(`TEST_TRACEABILITY_CURRENT=${rows.length}\n`);
} else {
  await fs.writeFile(outputPath, report, "utf8");
  process.stdout.write(`TEST_TRACEABILITY_WRITTEN=${rows.length}\n`);
}
