/** Monthly cost. Rates are placeholders: no vendor quote exists (W-0008). */
export function monthlyCost({ channels, simMonthlyCost, gatewayMonthlyCost, infraMonthlyCost }) {
  return (channels * simMonthlyCost) + gatewayMonthlyCost + infraMonthlyCost;
}

/**
 * Cost per confirmed order.
 *
 * Divides by CONFIRMED orders, not by calls. A pool that calls twice as often and confirms the
 * same number of orders costs twice as much per outcome, and dividing by calls would hide exactly
 * that.
 */
export function costPerConfirmedOrder({ monthly, confirmedOrdersPerMonth }) {
  return confirmedOrdersPerMonth === 0 ? null : monthly / confirmedOrdersPerMonth;
}
